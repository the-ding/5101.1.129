#define FLASH_SIZE             (32UL*1024*1024)
#define FLASH_ERASE_SIZE       (256UL*1024)

#define FLASH_HIST_START        0
#define FLASH_HIST_END          FLASH_SIZE/2

#define FLASH_ALARM_START       FLASH_SIZE/2
#define FLASH_ALARM_END         FLASH_SIZE

/*****************************************************************************/
/* 查询FLASH是否忙                                                           */
/*****************************************************************************/
BOOL  Flash_busy (void);

/*****************************************************************************/
/* 从FLASH任意地址读取指定长度数据                                           */
/*****************************************************************************/
void  Flash_read (UINT32 addr, void *buf, UINT16 bytes);

/*****************************************************************************/
/* 往FLASH任意地址写指定长度数据 (*不检查是否已经擦除*)                      */
/*****************************************************************************/
void  Flash_write(UINT32 addr, const void *buf, UINT16 bytes);

/*****************************************************************************/
/* 启动FLASH块擦除操作 (*注意：这里仅仅是启动了擦除，没有等待完成就返回了*)  */
/*****************************************************************************/
void  Flash_erase (UINT32 addr);

/*****************************************************************************/
/* FLASH模块初始化                                                           */
/*****************************************************************************/
void  Flash_Init (void);
